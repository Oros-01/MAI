#pragma once


#include <cstddef>    // нужен для std::size_t
#include <stdexcept>  // нужен для std::out_of_range (пока не используется,
                      // но понадобится в at(), front(), back())

// template <typename T> — объявление ШАБЛОНА класса.
// T — это "имя типа-заглушки", которое подставится позже.
// Когда ты напишешь MyVector<int>, компилятор сгенерирует
// отдельный класс, где везде вместо T стоит int.
// Когда напишешь MyVector<std::string> — другой класс, где T = std::string.
// Это называется "инстанцирование шаблона".
template <typename T>
class MyVector {
public:
    // using value_type = T;
    // Это НЕ переменная и НЕ объект. Это ПСЕВДОНИМ типа.
    // Просто говорим: "с этого момента value_type — это то же самое, что T".
    // Зачем? Чтобы снаружи можно было писать:
    //     MyVector<int>::value_type x = 5;   // x — это int
    // Это стандартное требование для контейнеров (у std::vector тоже есть).
    using value_type = T;

    // std::size_t — это беззнаковое целое (обычно unsigned long на 64-бит).
    // Вводим псевдоним size_type = std::size_t.
    using size_type = std::size_t;

    // ===================== КОНСТРУКТОР ПО УМОЛЧАНИЮ =====================
    // Вызывается, когда пишут: MyVector<int> v;
    // После двоеточия идёт СПИСОК ИНИЦИАЛИЗАЦИИ — так поля получают 
    // начальные значения ЕЩЁ ДО того, как выполнится тело конструктора {}.
    MyVector(): data_(nullptr), size_(0), capacity_(0)
            // элементов сейчас 0
            // data_ — указатель, ставим в "ничто"
            // вместимость (сколько влезет) тоже 0
    {
        // тело пустое — вся работа сделана в списке инициализации
    }

    // ========================= ДЕСТРУКТОР =========================
    // Вызывается автоматически, когда объект умирает:
    //   - вышли из области видимости (конец { ... })
    //   - удалили через delete
    //   - упал стек при исключении
    // Имя деструктора — тильда + имя класса: ~MyVector
    ~MyVector() {
        delete[] data_;
        // delete[] (именно с квадратными скобками!) освобождает массив,
        // который был выделен через new T[...].
        // Если data_ == nullptr, delete[] ничего не делает — это разрешено.
        // ВАЖНО: delete[] не удаляет сам объект MyVector. 
        // Он только освобождает память, на которую указывает data_,
        // то есть тот самый массив элементов T.
        // Сам объект MyVector живёт на стеке (или где его создали) 
        // и разрушается сам, по своим правилам.
    }

    // ======================== НАБЛЮДАТЕЛИ ========================
    // const после скобок означает: "этот метод не меняет объект".
    // Его можно вызывать у константного объекта.
    size_type size() const     { return size_; }
    size_type capacity() const { return capacity_; }
    bool      empty() const    { return size_ == 0; }

private:
    // ======================== ПОЛЯ КЛАССА ========================
    // Каждый объект MyVector хранит эти три значения у себя.
    T*        data_;      // адрес начала массива в куче (или nullptr)
    size_type size_;      // сколько РЕАЛЬНО лежит элементов
    size_type capacity_;  // сколько ВСЕГО поместится без перевыделения
};