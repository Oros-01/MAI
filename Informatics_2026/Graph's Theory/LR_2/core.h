#include <string>
#include <utility>
#include <vector>

// ---------------------------------------------------------------------
//  ЧАСТЬ 1. Транспортная сеть (максимальный поток)
// ---------------------------------------------------------------------

// Сеть хранится матрицей пропускных способностей.
// Вершины нумеруются с 1, поэтому матрица имеет размер (n + 1) x (n + 1),
// а нулевая строка и нулевой столбец просто не используются.
struct Network {
    int n = 0;                                 // количество вершин
    int source = 0;                            // источник
    int sink = 0;                              // сток
    std::vector<std::vector<long long>> cap;   // cap[u][v] — пропускная способность дуги u -> v

    // Есть ли в сети дуга u -> v (пропускная способность больше нуля).
    bool is_edge(int u, int v) const { return cap[u][v] > 0; }
};

// Чтение сети из файла.
// Первая строка файла — "<источник> <сток>".
// Тело файла может быть в одном из двух видов:
//   1) матрица пропускных способностей N x N        (наш нечётный вариант);
//   2) списки смежности "<вершина> <сосед> <вес> <сосед> <вес> ...".
// Формат определяется автоматически, поэтому подойдёт любой из них.
bool load_network(const std::string& fileName, Network& net);

// Форд-Фалкерсон (версия с поиском пути в ширину — Эдмондс-Карп).
// Возвращает величину максимального потока,
// в flow[u][v] оставляет поток по дуге u -> v.
long long ford_fulkerson(const Network& net, std::vector<std::vector<long long>>& flow);

// ---------------------------------------------------------------------
//  ЧАСТЬ 2. Карта высот (поиск пути)
// ---------------------------------------------------------------------

// Карта — прямоугольная таблица высот. Высота 0 означает, что прохода нет.
struct HeightMap {
    int rows = 0;
    int cols = 0;
    std::vector<std::vector<int>> h;   // h[r][c] — высота клетки

    // Лежит ли клетка внутри карты.
    bool inside(int r, int c) const {
        return r >= 0 && r < rows && c >= 0 && c < cols;
    }

    // Можно ли пройти через клетку (высота не ноль).
    bool passable(int r, int c) const { return h[r][c] != 0; }

    // Номер клетки: одна и та же формула для пары (строка, столбец) и обратно.
    int id(int r, int c) const { return r * cols + c; }
};

// Чтение карты из файла: каждая строка файла — строка карты,
// числа разделены пробелами. Короткие строки дополняются нулями (стенами).
bool load_map(const std::string& fileName, HeightMap& map);

// Результат работы одного алгоритма поиска пути.
struct PathResult {
    std::string name;                       // название алгоритма
    double length = -1.0;                   // длина пути; -1 — путь не найден
    std::vector<std::pair<int, int>> path;  // клетки пути: (строка, столбец)
    double visited_percent = 0.0;           // процент просмотренных вершин
    double time_ms = 0.0;                   // время работы в миллисекундах
};

// Поиск кратчайшего пути.
//   use_astar == false — Дейкстра;
//   use_astar == true  — A* с эвристикой Чебышева.
// Функция одна, потому что Дейкстра — это A* с нулевой эвристикой.
PathResult find_path(const HeightMap& map, int r1, int c1, int r2, int c2, bool use_astar);

// ---------------------------------------------------------------------
//  ЧАСТЬ 3. Двудольный граф (двудольность и максимальное паросочетание)
// ---------------------------------------------------------------------

// Граф хранится списками смежности, вершины нумеруются с 1,
// поэтому adj[0] не используется.
struct BipGraph {
    int n = 0;
    std::vector<std::vector<int>> adj;   // adj[u] — соседи вершины u
};

// Чтение графа из файла. Поддерживаются два формата:
//   1) первая строка — число вершин N, далее матрица смежности N x N;
//   2) список рёбер "u v" (по паре вершин в строке).
// Формат определяется автоматически.
bool load_bipgraph(const std::string& fileName, BipGraph& g);

// Двудольность: раскраска графа в 2 цвета обходом в ширину.
// В color[v] остаётся цвет вершины (0 или 1).
// Возвращает false, если граф не двудольный.
bool is_bipartite(const BipGraph& g, std::vector<int>& color);

// Максимальное паросочетание — алгоритм Куна (поиск увеличивающих цепей).
// color — раскраска из is_bipartite (левая доля — цвет 0).
// В matching складываются найденные рёбра.
// Возвращает размер максимального паросочетания.
int max_matching(const BipGraph& g, const std::vector<int>& color,
                 std::vector<std::pair<int, int>>& matching);
