#pragma once // защита от повторного #include

#include <string>
#include <vector>

// Одно ребро (или дуга) графа: откуда идёт, куда идёт и с каким весом.
struct Edge {
    int from;            // номер вершины, из которой выходит ребро
    int to;              // номер вершины, в которую входит ребро
    long long weight;    // вес ребра
};

// Класс "Граф".
// Файл читается как списки смежности, а внутри граф хранится
// в виде матрицы смежности (две матрицы: есть ли ребро и его вес).
class Graph {
public:
    // Создать пустой граф.
    // directed = true  - ориентированный граф (орграф),
    // directed = false - неориентированный граф.
    Graph(bool directed = false);

    // Создать граф и сразу прочитать его из файла.
    Graph(const std::string& fileName, bool directed);

    // Прочитать граф из файла. Старое содержимое графа стирается.
    // Возвращает false, если файл не удалось открыть или он пустой.
    bool loadFromFile(const std::string& fileName);


    void clear();    // Сделать граф пустым.


    bool isDirected() const;     // Ориентированный ли граф.


    int size() const;    // Количество вершин в графе.

    
    bool has_vertex(int v) const; // Есть ли в графе вершина с таким номером.

   
    bool is_edge(int a, int b) const; // Есть ли в графе ребро (дуга) между вершинами a и b.


    long long weight(int a, int b) const;// Вес ребра (дуги) между вершинами a и b
                                            // Если такого ребра нет, возвращается 0.

    
    bool add_vertex(int v);// Возвращает false, если такая вершина уже есть.
                            //  Добавить вершину с номером v.


    bool add_edge(int a, int b, long long w); // Добавить ребро между вершинами a и b с весом w.
                                             // Возвращает false, если вершины не существуют или это петля.



    bool remove_vertex(int v);   // Удалить вершину v вместе со всеми её рёбрами.
                                    // Номера остальных вершин при этом НЕ меняются.

    bool remove_edge(int a, int b);    // Удалить ребро между вершинами a и b.


    std::vector<int> vertices() const;     // Список номеров всех вершин графа (по возрастанию).



    std::vector<Edge> list_of_edges() const; // Список всех рёбер графа.
                                             // Для неориентированного графа каждое ребро встречается один раз.

                                             

    // Список рёбер, связанных с вершиной v.
    // Для неориентированного графа - все рёбра, в которые входит вершина v,
    // для ориентированного - все дуги, которые выходят из вершины v.
    std::vector<Edge> list_of_edges(int v) const;

private:
    bool directed_; // ориентированный ли граф

   
    std::vector<std::vector<bool> > is_edge_; // Матрица смежности: is_edge_[i][j] == true, если есть ребро i -> j.


    std::vector<std::vector<long long> > weight_; // Матрица весов: weight_[i][j] - вес ребра i -> j.

    
    std::vector<bool> exists_;// exists_[i] == true, если вершина с номером i существует.

   
    void ensure_size(int v); // Увеличить матрицы так, чтобы в них поместилась вершина с номером v.
};

